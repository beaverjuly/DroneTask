"""Render the selected Unicode emoji once to fixed PNG assets.

Run on macOS with Pillow and the installed Apple Color Emoji font. Runtime
and notebook use these same images, eliminating participant OS font changes.
No images are downloaded or generated by an image model.
"""
import json
import subprocess
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
FONT = Path('/System/Library/Fonts/Apple Color Emoji.ttc')


def render_items():
    export = json.loads(subprocess.check_output(
        ['node', str(ROOT/'design_checks/scripts/export_memory_screen.cjs')], text=True, cwd=ROOT))
    font = ImageFont.truetype(str(FONT), 160)
    for item in export['screen']['items']:
        canvas = Image.new('RGBA', (512, 512))
        ImageDraw.Draw(canvas).text((40, 40), item['emoji'], font=font, embedded_color=True)
        bounds = canvas.getbbox()
        if not bounds:
            raise ValueError(f"Empty glyph for {item['concept']}")
        glyph = canvas.crop(bounds)
        scale = 192 / max(glyph.size)
        glyph = glyph.resize(tuple(round(dimension * scale) for dimension in glyph.size),
                             Image.Resampling.LANCZOS)
        output = Image.new('RGBA', (256, 256))
        output.alpha_composite(glyph, ((256-glyph.width)//2, (256-glyph.height)//2))
        destination = ROOT/item['img']
        destination.parent.mkdir(parents=True, exist_ok=True)
        output.save(destination)
    print(f"Rendered {len(export['screen']['items'])} fixed emoji PNGs using {FONT.name}")


if __name__ == '__main__':
    render_items()
